create table public.equipment_units (
  id bigint generated by default as identity primary key,
  catalog_id bigint not null references public.equipment_catalog(id) on delete restrict,
  consecutive_code text not null unique,
  asset_number text unique,
  brand text,
  model text,
  serial_number text unique,
  equipment_use text,
  observations text,
  status text not null default 'available' check (status in ('available','loaned','maintenance','retired')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.loan_request_unit_assignments (
  id bigint generated by default as identity primary key,
  request_item_id bigint not null references public.student_loan_request_items(id) on delete cascade,
  equipment_unit_id bigint not null references public.equipment_units(id) on delete restrict,
  delivered_at timestamptz not null default now(),
  returned_at timestamptz,
  return_note text,
  returned_by text,
  unique (request_item_id, equipment_unit_id)
);

create table public.loan_year_counters (
  year integer primary key,
  last_number integer not null check (last_number > 0)
);

